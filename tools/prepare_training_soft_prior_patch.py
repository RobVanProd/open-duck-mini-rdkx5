#!/usr/bin/env python3
"""Prepare the Open Duck Playground soft-prior training patch.

Default mode is read-only: it validates the expected Joystick/runner insertion
points and prints unified diffs. Pass --apply to modify the sibling Playground
checkout. All inserted behavior is default-off.
"""

