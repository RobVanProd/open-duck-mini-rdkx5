def patch_runner(text: str) -> str:
    if "--enable_soft_prior" in text:
        return text
    text = replace_once(
        text,
        "import argparse\n\n",
        "import argparse\nimport json\nfrom pathlib import Path\n\n",
        "runner imports",
    )
    text = replace_once(
        text,
        "        config.reward_config.scales.target_rate = args.target_rate_scale\n",
        RUNNER_CONFIG_BLOCK + "        config.reward_config.scales.target_rate = args.target_rate_scale\n",
        "soft_prior runner config",
    )
    text = replace_once(
        text,
        '''    parser.add_argument(
        "--target_rate_scale",
''',
        RUNNER_ARG_BLOCK
        + '''    parser.add_argument(
        "--target_rate_scale",
''',
        "soft_prior runner args",
    )
    return text


def unified_diff(path: Path, rel: Path, before: str, after: str) -> str:
    return "".join(
        difflib.unified_diff(
            before.splitlines(keepends=True),
            after.splitlines(keepends=True),
            fromfile=f"a/{rel}",
            tofile=f"b/{rel}",
        )
    )


def prepare_file(path: Path, rel: Path, patcher) -> tuple[str, str, str]:
    if not path.exists():
        raise FileNotFoundError(path)
    before = path.read_text()
    after = patcher(before)
    return before, after, unified_diff(path, rel, before, after)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Prepare the default-off Open Duck Playground soft-prior training patch."
    )
    parser.add_argument("--playground-path", default=str(DEFAULT_PLAYGROUND))
    parser.add_argument("--apply", action="store_true", help="modify Playground files")
    parser.add_argument(
        "--check",
        action="store_true",
        help="validate patch generation without applying; default behavior",
    )
    args = parser.parse_args()

    playground = Path(args.playground_path).expanduser().resolve()
    joystick = playground / JOYSTICK_REL
    runner = playground / RUNNER_REL
    try:
        joystick_before, joystick_after, joystick_diff = prepare_file(
            joystick, JOYSTICK_REL, patch_joystick
        )
        runner_before, runner_after, runner_diff = prepare_file(runner, RUNNER_REL, patch_runner)
    except (FileNotFoundError, ValueError) as exc:
        print(f"HOLD_PATCH_CONTEXT_MISMATCH: {exc}", file=sys.stderr)
        return 3

    if joystick_after == joystick_before and runner_after == runner_before:
        print("PASS_ALREADY_PATCHED")
        return 0

    if args.apply:
        joystick.write_text(joystick_after)
        runner.write_text(runner_after)
        print(f"APPLIED {joystick}")
        print(f"APPLIED {runner}")
    else:
        if joystick_diff:
            print(joystick_diff)
        if runner_diff:
            print(runner_diff)
        print("PASS_PATCH_PREPARED", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
